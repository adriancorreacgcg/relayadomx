    public static boolean esAid(byte[] apdu) { return contiene(apdu, AID_TARJETA); }

    public static byte[] responder(byte[] apdu) {
        if (apdu.length < 4) return NO_SOPORTADO;
        int ins = apdu[1] & 0xff;
        if (ins == 0xA4) {
            if (contiene(apdu, AID_PPSE)) return PPSE;
            if (contiene(apdu, AID_TARJETA)) return variante == 2 ? FCI_MSD : FCI_EMV;
            return NO_ENCONTRADO;
        }
        if (ins == 0xA8) return variante == 2 ? GPO_MSD : GPO_EMV;
        if (ins == 0xB2) return variante == 2 ? NO_ENCONTRADO : REGISTRO;
        if (ins == 0xAE) return GENAC;
        return NO_SOPORTADO;
    }

    private static boolean contiene(byte[] datos, byte[] busca) {
        for (int i = 0; i + busca.length <= datos.length; i++) {
            boolean ok = true;
            for (int j = 0; j < busca.length; j++) {
                if (datos[i + j] != busca[j]) { ok = false; break; }
            }
            if (ok) return true;
        }
        return false;
    }
